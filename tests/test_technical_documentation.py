def test_every_cited_test_exists():
    cited = set(shared.CITED_TEST.findall(_text(DOCUMENT)))
    assert cited
    missing = [
        f"{path}::{name}" for path, name in sorted(cited)
        if not re.search(rf"^def {name}\(", _text(ROOT / path), re.M)
    ]
    assert missing == []


def test_the_last_appendix_is_the_evidence_report_the_harness_writes():
    results, stranger = shared._results()
    report = render_report(results, "commit", datetime(2026, 1, 1, tzinfo=timezone.utc), stranger)
    text = _text(DOCUMENT)
    assert text.index(APPENDIX) == text.rindex("\n## ") + 1, "the evidence report must be the last appendix"
    embedded = text[text.index(APPENDIX) :].split("\n", 1)[1]
    embedded = "\n".join(
        line for line in embedded.splitlines()
        if not line.startswith("The report below was generated") and not GENERATED.match(line)
    )
    assert [line for line in _demoted(report) if line.strip()] == [line for line in embedded.splitlines() if line.strip()]


def _check_ancestor(root: Path, commit: str) -> None:
    """Fail when the commit is not an ancestor of HEAD; skip when root is not itself a git checkout.

    A folder unpacked from a downloaded zip has no .git, and a copy inside another checkout would find that
    checkout's .git instead of its own, so the check runs only when git's top level is root itself.
    """
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=root, capture_output=True, text=True)
    if top.returncode != 0 or Path(top.stdout.strip()).resolve() != root.resolve():
        pytest.skip(f"The ancestor check needs a git checkout of this repository, and {root} is not one.")
    ancestor = subprocess.run(["git", "merge-base", "--is-ancestor", commit, "HEAD"], cwd=root, capture_output=True)
    assert ancestor.returncode == 0, f"{commit} is not an ancestor of HEAD"


def check_embedded_run(root: Path) -> None:
    appendix = _text(root / "docs" / DOCUMENT.name).split(APPENDIX, 1)[1]
    runs = EMBEDDED_RUN.findall(appendix)
    assert len(runs) == 1, "the appendix must keep exactly one Generated by line, naming a clean commit"
    moment, commit = runs[0]
    datetime.fromisoformat(moment)
    _check_ancestor(root, commit)


def test_the_appendix_names_the_commit_and_time_of_its_run_and_that_commit_is_an_ancestor_of_head():
    check_embedded_run(ROOT)


def test_without_a_git_checkout_the_ancestor_check_skips_and_says_why():
    copy = ROOT / ".harness_tmp" / "ancestor_check_copy"
    shutil.rmtree(copy, ignore_errors=True)
    (copy / "docs").mkdir(parents=True)
    shutil.copy(DOCUMENT, copy / "docs" / DOCUMENT.name)
    try:
        with pytest.raises(pytest.skip.Exception, match="needs a git checkout"):
            check_embedded_run(copy)
    finally:
        shutil.rmtree(copy, ignore_errors=True)


def test_a_commit_that_is_not_an_ancestor_of_head_still_fails_the_check():
    with pytest.raises(AssertionError, match="is not an ancestor of HEAD"):
        _check_ancestor(ROOT, "0" * 40)
