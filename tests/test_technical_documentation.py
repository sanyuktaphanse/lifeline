"""The technical documentation's numbers, citations and embedded evidence report, checked against their sources.

docs/technical_documentation.md is the submission document. It carries the same result numbers as the self
assessment, built by the same functions in tests/test_self_assessment.py, and adds the suite, language,
knowledge, scenario, tier and fixture counts, the FISCO BCOS block numbers, and the whole evidence report as its
last appendix. These tests rebuild each from its source and fail when the document no longer says it, when a
cited test is gone, or when the embedded report no longer matches what the harness writes.
"""

import re
import shutil
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import pytest
import yaml

from contracts.schemas import ActionType
from core.harness import FAILED, NOT_AUTOMATED, PASSED, render_report
from core.tiers import TIERS
from tests import test_self_assessment as shared

ROOT = Path(__file__).resolve().parent.parent
DOCUMENT = ROOT / "docs" / "technical_documentation.md"
CHAIN_README = ROOT / "chain" / "README.md"
FIXTURE = ROOT / "fixtures" / "demo_user.yaml"
KNOWLEDGE = ROOT / "rails" / "knowledge"
SCENARIOS = ROOT / "suites" / "scenarios"
APPENDIX = "## Appendix C. The evidence report"
GENERATED = re.compile(r"^Generated by `core/harness.py` at .*$", re.M)
# The line the appendix keeps from the run it embeds: its time and a commit with nothing uncommitted.
EMBEDDED_RUN = re.compile(r"^Generated by `core/harness.py` at (\S+) from commit `([0-9a-f]{40})`\.$", re.M)
# The FISCO BCOS facts the document repeats, each as chain/README.md words it.
CHAIN_FACTS = (
    "deployed the contract in block 1",
    "anchored a head in block 3",
    "stopped making blocks at block 5",
    "was anchored in block 7",
)


def _text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def tasks_sentence() -> str:
    tasks = [result for result in shared._results()[0] if result.suite == "tasks"]
    counts = Counter(result.status for result in tasks)
    missing = [result.id for result in tasks if result.status == NOT_AUTOMATED]
    return (
        f"Of the {len(tasks)} tasks in `suites/tasks.yaml`, {counts[PASSED]} pass, {counts[FAILED]} fail and "
        f"{len(missing)} are not automated: {', '.join(missing)}."
    )


def languages_sentence() -> str:
    runs = [run for result in shared._results()[0] for run in result.runs]
    count = {lang: sum(lang in run.langs for run in runs) for lang in ("en", "pt", "zh")}
    return (
        f"Their runs count {count['en']} in English, {count['pt']} in Portuguese and {count['zh']} in Chinese, "
        "a run that switches language counted under each."
    )


def knowledge_sentence() -> str:
    files = sorted(KNOWLEDGE.glob("*.yaml"))
    entries = [entry for path in files for entry in yaml.safe_load(_text(path))]
    checkers = Counter(entry["checked_by"] for entry in entries)
    second = sum(bool(entry["second_check_by"]) for entry in entries)
    return (
        f"`rails/knowledge/` holds {len(entries)} entries in {len(files)} files, {checkers['CC']} checked once by "
        f"Claude Code and {checkers['SP']} by SP, and {second or 'none'} with a second check."
    )


def scenarios_sentence() -> str:
    top = sorted(SCENARIOS.glob("*.yaml"))
    live = sum((yaml.safe_load(_text(path)) or {}).get("live") is True for path in top)
    stranger = len(list((SCENARIOS / "stranger").glob("*.yaml")))
    return f"`suites/scenarios/` holds {len(top)} scenario files, {live} of them marked live, and {stranger} stranger files."


def tiers_sentence() -> str:
    tiers = Counter(tier.value for tier in TIERS.values())
    return (
        f"Each of the {len(ActionType)} action types has one tier: {tiers['T0']} at T0, {tiers['T1']} at T1, "
        f"{tiers['T2']} at T2 and {tiers['T3']} at T3."
    )


def fixture_sentence() -> str:
    mandate = yaml.safe_load(_text(FIXTURE))["mandate"]
    return (
        f"a per transaction limit of {int(mandate['per_txn_limit']):,} SGD, a daily limit of "
        f"{int(mandate['daily_limit']):,} SGD and a cooling period of {mandate['cooling_hours']} hours"
    )


def _demoted(report: str) -> list[str]:
    """The report as the appendix holds it: its headings two levels down, its generated line left out."""
    lines = GENERATED.sub("", report).splitlines()
    return [re.sub(r"^(#+) ", lambda m: "#" * (len(m[1]) + 2) + " ", line) for line in lines]


def _section(heading: str) -> str:
    text = _text(DOCUMENT)
    start = text.index(f"\n## {heading}\n")
    return text[start : text.index("\n## ", start + 1)]


