"""Write the Wise sandbox operation log the submission asks for as execution evidence.

`make evidence-wise` runs it. It drives the Wise sandbox rail through the same Rail and Router interfaces the agent
uses: one quote, one paid transfer traced through Wise's simulated statuses to sent, and one transfer cancelled.
Every row is what the sandbox answered at that moment. It refuses to start without WISE_SANDBOX_TOKEN, and the
token never reaches the log. Source: docs/hackathon/rules.md, section 5, item 6.
"""

import argparse
import subprocess
import sys
import uuid
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any

from contracts.errors import RailError
from core.model_adapter import environment
from rails.fake_router import FakeRouter
from rails.wise_sandbox import SANDBOX_STEP, STATUS_SOURCE, WiseSandboxClient, WiseSandboxConfig, WiseSandboxRail, WiseSandboxRouter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "evidence" / "wise-sandbox.md"
# Fixture: the run sends a small allowance to the student's own Singapore account, the corridor and purpose the
# demo mandate allows for the emergency allowance. Not a figure about Wise.
PAYEE = "self_sg"
CORRIDOR = "SG>SG"
AMOUNT = Decimal("25")
PURPOSE = "emergency"
MANDATE_REF = "mandate-student_001-wise-sandbox-evidence"
# The order Wise's simulation endpoints move a transfer along. Source: STATUS_SOURCE, "Testing transfer statuses".
SIMULATED = ("processing", "funds_converted", "outgoing_payment_sent")


def _commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def run(client: WiseSandboxClient, payee: str, out: Path) -> list[dict[str, Any]]:
    if payee not in client.config.recipients:
        raise SystemExit(f"No Wise sandbox recipient is set for {payee!r} in WISE_SANDBOX_RECIPIENTS.")
    rail = WiseSandboxRail(client, client.config.recipients)
    rows: list[dict[str, Any]] = []

    def log(step: str, detail: str, result: str) -> None:
        rows.append({"at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "step": step, "detail": detail, "result": result})

    route = next(r for r in WiseSandboxRouter(FakeRouter(), client).quote(CORRIDOR, AMOUNT, PURPOSE, "normal") if r.rail == "wise")
    route = route.model_copy(update={"payee_id": payee})
    log("quote", f"{AMOUNT} {route.currency_from} to {route.currency_to}", f"fee {route.fee}, {route.rate_source or route.blocked_reason}")
    run_id = uuid.uuid4().hex[:8]
    try:
        receipt = rail.execute(route, MANDATE_REF, f"evidence-{run_id}-pay", "evidence")
        log("execute", f"pay {payee}", f"receipt {receipt.receipt_id}, {receipt.status.value}, simulated {receipt.simulated}")
        log("trace", receipt.receipt_id, " ".join(rail.status(receipt.receipt_id).next_steps[:1]))
        for status in SIMULATED:
            try:
                rail.simulate(receipt.receipt_id, status)
                log("simulate", f"{receipt.receipt_id} to {status}", "accepted")
            except RailError as error:
                log("simulate", f"{receipt.receipt_id} to {status}", f"refused: {error}")
            trace = rail.status(receipt.receipt_id)
            log("trace", receipt.receipt_id, f"{trace.next_steps[0]} Lifeline reads it as {trace.status.value}.")
        second = rail.execute(route, MANDATE_REF, f"evidence-{run_id}-cancel", "evidence")
        log("execute", f"pay {payee}, to cancel", f"receipt {second.receipt_id}, {second.status.value}")
        result = rail.cancel(second.receipt_id)
        log("cancel", second.receipt_id, f"{result.status.value}{': ' + result.reason if result.reason else ''}")
        log("trace", second.receipt_id, " ".join(rail.status(second.receipt_id).next_steps[:1]))
    except RailError as error:
        log("error", "the run stopped", str(error))
    _write(out, rows)
    return rows


def _write(out: Path, rows: list[dict[str, Any]]) -> None:
    lines = [
        "# Wise sandbox operation log",
        "",
        f"Generated by `rails/wise_sandbox_evidence.py` at {datetime.now(timezone.utc).isoformat(timespec='seconds')} "
        f"from commit `{_commit()}`. {SANDBOX_STEP} Every row is what the Wise sandbox answered at that moment. "
        f"Wise's statuses are read as described at {STATUS_SOURCE}.",
        "",
        "| Time (UTC) | Step | Detail | Result |",
        "| --- | --- | --- | --- |",
        *(f"| {row['at']} | {row['step']} | {row['detail']} | {str(row['result']).replace('|', '/')} |" for row in rows),
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--payee", default=PAYEE)
    args = parser.parse_args(argv)
    config = WiseSandboxConfig.from_env(environment(None))
    if config is None:
        raise SystemExit("The Wise sandbox evidence run needs WISE_SANDBOX_TOKEN in .env; see .env.example.")
    rows = run(WiseSandboxClient(config), args.payee, args.out)
    print(f"{args.out}: {len(rows)} steps, {sum(row['step'] == 'error' for row in rows)} errors")


if __name__ == "__main__":
    main(sys.argv[1:])
