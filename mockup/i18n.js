const TABLES = { en, pt, zh };
let current = "en";
export const getLang = () => current;
export function setLang(code) { if (TABLES[code]) current = code; document.documentElement.lang = code === "zh" ? "zh-Hans" : code; }

// t("key") or t("key", { n: 3 }); a missing key falls back to English.
export function t(key, vars) {
  const v = TABLES[current][key] ?? en[key];
  if (typeof v !== "string" || !vars) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
